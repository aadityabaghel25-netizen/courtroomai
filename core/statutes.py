"""
Statute mapping lookup (IPC -> BNS, CrPC -> BNSS) from a data file supplied by
the project owner. Mappings are never generated by a model; if the file or the
row is missing the claim is "unverified" with "no mapping found".

File: data/statutes/ipc_bns_map.csv (built by scripts/build_statute_map.py) with columns
  old_act,old_section,new_act,new_section,title,source,ik_agrees
"""

import csv
import re
from datetime import date
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from core.claims import Claim, ClaimType, MappingRow, Status
from core.config import settings

# Bharatiya Nyaya Sanhita, BNSS and BSA came into force on this date.
NEW_CODES_IN_FORCE = date(2024, 7, 1)

_ACT_ALIASES = {
    "ipc": "IPC", "i.p.c": "IPC", "i.p.c.": "IPC", "indian penal code": "IPC",
    "crpc": "CrPC", "cr.p.c": "CrPC", "cr.p.c.": "CrPC", "code of criminal procedure": "CrPC",
    "bns": "BNS", "bharatiya nyaya sanhita": "BNS",
    "bnss": "BNSS", "bharatiya nagarik suraksha sanhita": "BNSS",
    "bsa": "BSA", "bharatiya sakshya adhiniyam": "BSA",
    "iea": "IEA", "indian evidence act": "IEA", "evidence act": "IEA",
}


def canon_act(act: str) -> str:
    """'Bharatiya Nyaya Sanhita, 2023' / 'The Indian Penal Code, 1860' / 'I.P.C.' -> 'BNS' / 'IPC'."""
    a = act.strip().lower()
    a = re.sub(r"^the\s+", "", a)
    a = re.sub(r",?\s*\(?\d{4}\)?\s*$", "", a).strip(" ,.")
    return _ACT_ALIASES.get(a, _ACT_ALIASES.get(a + ".", act.strip().upper()))


def canon_section(sec: str) -> str:
    return re.sub(r"\s+", "", sec).upper()


class StatuteMap:
    def __init__(self, rows: List[Dict[str, str]]):
        self.rows = rows
        self._index: Dict[Tuple[str, str], int] = {}
        for i, r in enumerate(rows):
            self._index[(canon_act(r["old_act"]), canon_section(r["old_section"]))] = i

    @classmethod
    def load(cls, path: Optional[Path] = None) -> "StatuteMap":
        path = path or settings.statute_map_path
        if not path.exists():
            return cls([])
        with open(path, newline="", encoding="utf-8") as f:
            return cls(list(csv.DictReader(f)))

    @property
    def available(self) -> bool:
        return bool(self.rows)

    def reverse(self, new_act: str, new_section: str) -> List[Dict[str, str]]:
        """Old-code rows whose new section is this one (e.g. BNS 304 -> the IPC rows mapped to 304)."""
        base = re.match(r"\d+", canon_section(new_section))
        if not base:
            return []
        out = []
        for r in self.rows:
            if canon_act(r["new_act"]) != canon_act(new_act):
                continue
            news = {m.group(0) for m in re.finditer(r"\d+", r["new_section"].split("(")[0])} | {
                re.match(r"\d+", x.strip()).group(0) for x in r["new_section"].split(",") if re.match(r"\d+", x.strip())}
            if base.group(0) in news:
                out.append(r)
        return out

    def lookup(self, act: str, section: str) -> Optional[Tuple[int, Dict[str, str]]]:
        i = self._index.get((canon_act(act), canon_section(section)))
        return None if i is None else (i, self.rows[i])


def _human(d: date) -> str:
    return f"{d.day} {d.strftime('%B %Y')}"


def statute_claim(claim_id: str, act: str, section: str, offence_date: Optional[date],
                  smap: StatuteMap) -> Claim:
    """
    Build a statute_mapping claim for one section cited in the FIR.
    Offences before 1 July 2024 stay under the old code; the BNS/BNSS counterpart
    is shown only if it is in the mapping file.
    """
    act_c, sec_c = canon_act(act), canon_section(section)
    if act_c not in ("IPC", "CrPC", "IEA", "BNS", "BNSS", "BSA"):
        # Only the IPC, CrPC and Evidence Act were replaced on 1 July 2024; other Acts keep their numbers.
        return Claim(id=claim_id, type=ClaimType.statute_mapping,
                     text=f"Section {sec_c} of the {act.strip()} is cited in the FIR; this Act was not part of the 1 July 2024 change, so its section number is unchanged.",
                     status=Status.passed, reason="only the IPC, CrPC and Evidence Act were replaced by BNS, BNSS and BSA")
    if act_c in ("BNS", "BNSS", "BSA"):
        return Claim(id=claim_id, type=ClaimType.statute_mapping,
                     text=f"Section {sec_c} {act_c} is cited in the FIR.",
                     status=Status.passed, reason="section is already under the new code; no mapping needed")
    hit = smap.lookup(act_c, sec_c)
    if hit is None:
        return Claim(id=claim_id, type=ClaimType.statute_mapping,
                     text=f"Section {sec_c} {act_c}: no mapping found.",
                     status=Status.unverified,
                     reason="no mapping found" + ("" if smap.available else " (the official IPC to BNS table has not been loaded yet)"))
    i, row = hit
    if row.get("ik_agrees") == "no":
        return Claim(id=claim_id, type=ClaimType.statute_mapping,
                     text=f"Section {sec_c} {act_c}: the official table gives Section {row['new_section']} {row['new_act']}, but a second source differs.",
                     evidence=[MappingRow(row_id=str(i), old_act=act_c, old_section=sec_c, new_act=row["new_act"],
                                          new_section=row["new_section"], source=row.get("source", ""))],
                     status=Status.weak, reason="the two mapping sources differ for this section; check the Act before relying on it")
    if offence_date is None:
        regime = "the offence date was not found in the FIR, so the applicable code is not decided"
    elif offence_date < NEW_CODES_IN_FORCE:
        regime = f"the offence date ({_human(offence_date)}) is before 1 July 2024, so {act_c} applies"
    else:
        regime = f"the offence date ({_human(offence_date)}) is on or after 1 July 2024, so {row['new_act']} applies"
    return Claim(
        id=claim_id, type=ClaimType.statute_mapping,
        text=f"Section {sec_c} {act_c} corresponds to Section {row['new_section']} {row['new_act']}; {regime}.",
        evidence=[MappingRow(row_id=str(i), old_act=act_c, old_section=sec_c, new_act=row["new_act"],
                             new_section=row["new_section"], source=row.get("source", ""))],
        status=Status.passed, reason="found in mapping table",
    )
